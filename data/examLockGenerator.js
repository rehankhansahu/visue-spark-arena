    '  echo netsh advfirewall firewall delete rule name="VSpark_Block_Outbound" ^>nul 2^>^&1',
    '  echo Restoring hosts configuration...',
    '  echo if exist "%LOCALAPPDATA%\\VSpark\\hosts.vspark.bak" copy /y "%LOCALAPPDATA%\\VSpark\\hosts.vspark.bak" "%SystemRoot%\\System32\\drivers\\etc\\hosts" ^>nul 2^>^&1',
    '  echo powershell -NoProfile -Command "if (Test-Path $env:SystemRoot\\System32\\drivers\\etc\\hosts) { (Get-Content $env:SystemRoot\\System32\\drivers\\etc\\hosts) | Where-Object { $_ -notmatch \'V SPARK 2026\' -and $_ -notmatch \'chatgpt\' -and $_ -notmatch \'claude\' -and $_ -notmatch \'deepseek\' -and $_ -notmatch \'github\' -and $_ -notmatch \'stackoverflow\' -and $_ -notmatch \'whatsapp\' -and $_ -notmatch \'youtube\' } | Set-Content $env:SystemRoot\\System32\\drivers\\etc\\hosts -Force -ErrorAction SilentlyContinue }" ^>nul 2^>^&1',
