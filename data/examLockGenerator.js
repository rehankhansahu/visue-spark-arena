    '',
    'echo [3/5] Restoring hosts file & clearing DNS blocklists...',
    'if exist "%LOCALAPPDATA%\\VSpark\\hosts.vspark.bak" (',
    '    copy /y "%LOCALAPPDATA%\\VSpark\\hosts.vspark.bak" "%SystemRoot%\\System32\\drivers\\etc\\hosts" >nul 2>&1',
