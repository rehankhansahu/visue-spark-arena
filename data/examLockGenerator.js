    'while ($running) {',
    '    Start-Sleep -Seconds 2',
    '    if (Test-Path "$env:LOCALAPPDATA\\VSpark\\unlock.signal") {',
    '        $reason = \'Manual Unlock Signal Received\'',
    '        $running = $false',
    '        break',
    '    }',
    '    try {',
    '        $body = @{ passKey = $pKey; username = $pKey } | ConvertTo-Json',
    '        $res = Invoke-RestMethod -Uri "$sUrl/api/team/pc-heartbeat" -Method Post -Body $body -ContentType \'application/json\' -TimeoutSec 5',
    '        if ($res.success) {',
    '            if ($res.shouldUnlock -eq $true -or $res.isCompleted -eq $true -or $res.allSolved -eq $true -or $res.leftArena -eq $true -or $res.teamStatus -eq \'left_early\' -or $res.contestStatus -eq \'ended\' -or ($res.remainingSeconds -ne $null -and $res.remainingSeconds -le 0)) {',
    '                $reason = if ($res.unlockReason) { $res.unlockReason } elseif ($res.leftArena -eq $true -or $res.teamStatus -eq \'left_early\') { \'You Left the Contest (Session Closed)\' } elseif ($res.isCompleted -eq $true -or $res.allSolved -eq $true) { \'All Challenges Completed! Congratulations!\' } else { \'Contest Time Up (Timer Ended)\' }',
    '                $running = $false',
    '            }',
    '        }',
    '    } catch {}',
    '}',
    '',
    '# 1. Reset Windows Firewall',
    'netsh advfirewall set allprofiles firewallpolicy blockinbound,allowoutbound | Out-Null',
    'netsh advfirewall firewall delete rule name=\'VSpark_Allow_DNS\' | Out-Null',
    'netsh advfirewall firewall delete rule name=\'VSpark_Allow_DNS_TCP\' | Out-Null',
    'netsh advfirewall firewall delete rule name=\'VSpark_Allow_DHCP\' | Out-Null',
